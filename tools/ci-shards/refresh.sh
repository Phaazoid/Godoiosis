#!/usr/bin/env bash
# Rewrites times.tsv beside this script: how long each test suite takes on CI, the weights deal.sh
# deals the shards by. Run by hand, never by CI, so ordinary work never dirties the tree.
#
#   bash tools/ci-shards/refresh.sh [runs]     # default 5
#
# Reads the logs of the last <runs> successful push runs of Tests on main (GitHub keeps logs 90
# days) and writes each suite's MEDIAN across them. Every job lands on its own VM, and one run's
# shards have measured 1.3-1.55x slower than another's, so a single run would weigh a whole shard's
# suites by its runner's luck.
#
# A suite's time is the wall clock from its `Run Test Suite:` line to the next suite's (or to
# `Overall Summary`), so it carries the per-suite overhead gdUnit4's own statistic leaves out.
# Needs `gh`, signed in.

set -euo pipefail
export LC_ALL=C

here=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
runs=${1:-5}
out=$here/times.tsv

repo=$(gh repo view --json nameWithOwner -q .nameWithOwner)
run_ids=$(gh run list -R "$repo" --workflow tests.yml --branch main --event push --status success \
  --limit "$runs" --json databaseId -q '.[].databaseId')
if [ -z "$run_ids" ]; then
  echo "refresh.sh: no successful push runs of Tests on main to read." >&2
  exit 1
fi

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

for run in $run_ids; do
  for job in $(gh run view "$run" -R "$repo" --json jobs -q '.jobs[].databaseId'); do
    echo "reading run $run, job $job" >&2
    gh api "repos/$repo/actions/jobs/$job/logs" | sed 's/\x1b\[[0-9;]*m//g' | awk '
      function secs(ts,   s) {
        s = substr(ts, 18); sub(/Z.*/, "", s)
        return substr(ts, 12, 2) * 3600 + substr(ts, 15, 2) * 60 + s
      }
      /Run Test Suite: res:\/\// || /Overall Summary/ {
        t = secs($1)
        if (suite != "") {
          d = t - start
          if (d < 0) d += 86400
          printf "%s\t%d\n", suite, d * 1000 + 0.5
        }
        suite = ""
        if ($0 ~ /Run Test Suite: / && match($0, /res:\/\/[^ ]*\.gd/)) {
          suite = substr($0, RSTART, RLENGTH)
          start = t
        }
      }' >> "$work/samples.tsv"
  done
done

if [ ! -s "$work/samples.tsv" ]; then
  echo "refresh.sh: no suite timings found in the logs. Did gdUnit4's log lines change?" >&2
  exit 1
fi

{
  echo "# Seconds each test suite takes on CI: the weights tools/ci-shards/deal.sh deals shards by."
  echo "# GENERATED by tools/ci-shards/refresh.sh on $(date -u +%F), the median of Tests runs"
  echo "# $(echo $run_ids | tr ' ' ','). Do not hand-edit; re-run refresh.sh."
  sort -t$'\t' -k1,1 -k2,2n "$work/samples.tsv" | awk -F'\t' '
    function flush(   m) {
      if (n == 0) return
      m = (n % 2) ? v[(n + 1) / 2] : (v[n / 2] + v[n / 2 + 1]) / 2
      printf "%s\t%.3f\n", path, m / 1000
    }
    $1 != path { flush(); path = $1; n = 0 }
    { v[++n] = $2 }
    END { flush() }'
} > "$work/times.tsv"

mv "$work/times.tsv" "$out"
echo "wrote $out: $(grep -vc '^#' "$out") suites from runs $(echo $run_ids | tr ' ' ',')" >&2
